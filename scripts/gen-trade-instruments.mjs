function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mockPrice(symbol, currency) {
  const h = hashStr(symbol);
  const u = (h % 10000) / 10000;
  const ranges = {
    USD: [8, 520],
    TRY: [12, 980],
    RUB: [40, 18000],
    EUR: [5, 420],
    GBP: [40, 2800],
  };
  const [lo, hi] = ranges[currency] || ranges.USD;
  let p = lo + u * (hi - lo);
  // ETF-ish lower mid for known ETF symbols handled separately
  if (currency === "RUB" && p > 8000) p = 80 + (h % 4000);
  return Math.round(p * 100) / 100;
}

function mockChange(symbol) {
  const h = hashStr(symbol + ":chg");
  const v = ((h % 700) - 350) / 100; // -3.50 .. +3.49
  return Math.round(v * 100) / 100;
}

function make(symbol, name, type, exchange, currency, popular) {
  return {
    symbol,
    name,
    type,
    price: mockPrice(symbol, currency),
    changePct: mockChange(symbol),
    exchange,
    currency,
    popular: popular || undefined,
  };
}

